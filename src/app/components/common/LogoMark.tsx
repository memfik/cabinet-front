/** Расстояние до самой дальней точки — по нему считается задержка волны. */
const REACH = 205

/**
 * Анимированный знак бренда: точки по очереди «пульсируют» волной от центра к краям.
 * Размер задаётся через `className`; цвет — `text-*` (точки берут currentColor).
 */
export function LogoMark({className}: {className?: string}) {
  return (
    <svg viewBox="-210 -210 420 420" aria-hidden className={cn("fill-current", className)}>
      {DOTS.map(([x, y, r]) => (
        <circle
          key={`${x}:${y}`}
          cx={x}
          cy={y}
          r={r}
          className="logo-dot"
          style={{animationDelay: `${((Math.hypot(x, y) / REACH) * 2.4).toFixed(2)}s`}}
        />
      ))}
    </svg>
  )
}
